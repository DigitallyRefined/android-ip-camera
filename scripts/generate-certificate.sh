#!/bin/bash

# Android IP Camera - Certificate Generator
# This script generates a secure certificate for Android IP Camera

echo "=============================================="
echo "Android IP Camera - Certificate Generator"
echo "=============================================="
echo
echo "This script will create a secure TLS certificate."
echo
echo "SECURITY NOTES:"
echo "- You will be prompted to create a strong certificate password"
echo "- The certificate will match the format generated by the app on first launch"
echo "- Certificate can be used for personal or development setups"
echo

# Set variables
CERT_DIR="certificates"
CERT_NAME="personal_certificate"
DAYS_VALID=3650
SUBJECT="/CN=localhost/O=Custom Android IP Camera Certificate/OU=Home/L=Home/ST=Personal/C=US"

# Create certificates directory if it doesn't exist
mkdir -p "$CERT_DIR"

# Prompt user for certificate password
read -rsp "Enter a strong password for the certificate: " PASSWORD
echo
read -rsp "Confirm password: " PASSWORD_CONFIRM
echo

# Check if passwords match
if [ "$PASSWORD" != "$PASSWORD_CONFIRM" ]; then
    echo "ERROR: Passwords do not match!"
    exit 1
fi

# Pass the password through the environment so spaces and special characters are not
# interpreted by the shell or exposed on the command line.
export CERT_PASSWORD="$PASSWORD"

echo "Generating secure certificate (matching app-generated format)..."
echo

# Generate private key and self-signed certificate matching app's CertificateHelper
openssl req -new -x509 \
    -newkey rsa:2048 \
    -keyout "$CERT_DIR/$CERT_NAME.key" \
    -out "$CERT_DIR/$CERT_NAME.crt" \
    -days $DAYS_VALID \
    -sha256 \
    -subj "$SUBJECT" \
    -passout env:CERT_PASSWORD

# Decrypt private key to plain PEM (matches typical app expectations)
openssl rsa -in "$CERT_DIR/$CERT_NAME.key" -out "$CERT_DIR/$CERT_NAME.key.plain" -passin env:CERT_PASSWORD 2>/dev/null && mv "$CERT_DIR/$CERT_NAME.key.plain" "$CERT_DIR/$CERT_NAME.key"

# Generate PKCS12 format with user-provided password (alias matches app)
# Use legacy algorithms for broader compatibility (LibreSSL/OpenSSL)
openssl pkcs12 -export \
    -in "$CERT_DIR/$CERT_NAME.crt" \
    -inkey "$CERT_DIR/$CERT_NAME.key" \
    -out "$CERT_DIR/$CERT_NAME.p12" \
    -name "$CERT_NAME" \
    -passout env:CERT_PASSWORD \
    -certpbe PBE-SHA1-3DES \
    -keypbe PBE-SHA1-3DES \
    -macalg SHA1 \
    -legacy 2>/dev/null || openssl pkcs12 -export \
    -in "$CERT_DIR/$CERT_NAME.crt" \
    -inkey "$CERT_DIR/$CERT_NAME.key" \
    -out "$CERT_DIR/$CERT_NAME.p12" \
    -name "$CERT_NAME" \
    -passout env:CERT_PASSWORD

echo
echo "=============================================="
echo "Certificate Generation Complete!"
echo "=============================================="
echo
echo "Files created:"
echo "  - $CERT_DIR/$CERT_NAME.key (Encrypted private key)"
echo "  - $CERT_DIR/$CERT_NAME.crt (Certificate)"
echo "  - $CERT_DIR/$CERT_NAME.p12 (PKCS12 format to import into the app)"
echo
